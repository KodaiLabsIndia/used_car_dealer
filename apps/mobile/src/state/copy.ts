export type Language = "en" | "hi" | "mr";
export type CopyKey = keyof typeof english;
export const languageNames = {
  en: "English",
  hi: "हिंदी",
  mr: "मराठी",
} as const;
export const localeFor = (language: Language) =>
  ({ en: "en-IN", hi: "hi-IN", mr: "mr-IN" })[language];
export const isLanguage = (value: unknown): value is Language =>
  value === "en" || value === "hi" || value === "mr";
export const words = (language: Language) => (key: CopyKey) =>
  language === "mr"
    ? marathi[key]
    : language === "hi"
      ? hindi[key]
      : english[key];
