"""Package the editable preview as one offline HTML file; no build dependencies."""
from pathlib import Path
import base64
import json

root = Path(__file__).resolve().parent

def data_url(path, mime):
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode()

html = (root / "index.html").read_text()
tokens_css = (root / "brand-tokens.css").read_text()
css = (root / "styles.css").read_text()
collection_css = (root / "collection.css").read_text()
script = (root / "app.js").read_text() + "\n" + (root / "drive-story.js").read_text()
tokens_css = tokens_css.replace("assets/plus-jakarta-sans.ttf", data_url(root / "assets" / "plus-jakarta-sans.ttf", "font/ttf"))
logo_url = data_url(root / "assets" / "arihant-logo.png", "image/png")
script = script.replace('src="assets/arihant-logo.png"', f'src="{logo_url}"')
html = html.replace("assets/arihant-logo.png", logo_url)
html = html.replace("assets/journey-car.png", data_url(root / "assets" / "journey-car.png", "image/png"))
assets = {name: data_url(root / "assets" / f"{name}.jpg", "image/jpeg") for name in ("sonet", "seltos")}
script = "const previewAssets = " + json.dumps(assets) + ";\n" + script
script = script.replace('src="assets/${car}.jpg"', 'src="${previewAssets[car]}"')
html = html.replace('<link rel="stylesheet" href="brand-tokens.css" />', f"<style>{tokens_css}</style>")
html = html.replace('<link rel="stylesheet" href="styles.css" />', f"<style>{css}</style>")
html = html.replace('<link rel="stylesheet" href="collection.css" />', f"<style>{collection_css}</style>")
html = html.replace('<script src="app.js" defer></script>', "")
html = html.replace('<script src="drive-story.js" defer></script>', "")
html = html.replace("</body>", "<script>" + script.replace("</script", "<\\/script") + "</script>\n</body>")
html = html.replace("<!doctype html>", "<!doctype html>\n<!-- Generated by build-preview.py. Edit index.html, styles.css, and app.js. -->")
output = root / "preview.html"
output.write_text(html)
print(f"Created {output.name}: {output.stat().st_size:,} bytes; images, fonts, styles, and interactions embedded.")
